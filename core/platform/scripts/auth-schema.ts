// Writes src/auth-schema.sql: the SQL Better Auth needs for its tables, from the same options the worker uses.
// Run with `pnpm --filter platform auth:schema` after changing plugins or fields; ensurePlatform() applies the file at boot.
import Database from "better-sqlite3";
import { getMigrations } from "better-auth/db/migration";
import { writeFileSync } from "node:fs";
import { resolve } from "node:path";
import { createAuthOptions } from "../src/auth-options";

const options = createAuthOptions({ database: new Database(":memory:"), secret: "schema-only", baseURL: "http://localhost:5300" });
const { compileMigrations } = await getMigrations(options);
const sql = await compileMigrations();
const out = resolve(import.meta.dirname, "../src/auth-schema.sql");
writeFileSync(out, `-- Generated by scripts/auth-schema.ts from src/auth-options.ts. Do not edit.\n${sql}`);
console.log(`wrote ${out} (${sql.split(";").filter((s) => s.trim()).length} statements)`);
