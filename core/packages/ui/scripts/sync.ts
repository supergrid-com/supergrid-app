// Copies the desktop app's base-ui components into this kit with relative imports, so the kit and the
// app are one set of components. Run from core/: `pnpm -s ui:sync`. The chat composer stays out: it is
// the agent's input, not a kit component.
import { mkdirSync, readdirSync, readFileSync, writeFileSync, rmSync } from "node:fs";
import { join, resolve } from "node:path";
import { defaultTheme, themeToCss } from "../../theme/index";

const here = resolve(import.meta.dirname ?? ".");
const root = resolve(here, "../../../..");
const from = join(root, "app/src/renderer/app");
const to = join(here, "../src");
const SKIP = new Set(["composer.tsx"]);

const rewrite = (src: string) =>
  src
    .replace(/from "~\/lib\/utils"/g, 'from "./utils"')
    .replace(/from "~\/components\/ui\/([\w-]+)"/g, 'from "./$1"')
    .replace(/from "~\/hooks\/use-media-query"/g, 'from "./use-media-query"');

const files = readdirSync(join(from, "components/ui")).filter((f) => f.endsWith(".tsx") && !SKIP.has(f));
for (const f of readdirSync(to)) if (f.endsWith(".tsx")) rmSync(join(to, f));
mkdirSync(to, { recursive: true });
for (const f of files) writeFileSync(join(to, f), rewrite(readFileSync(join(from, "components/ui", f), "utf8")));
writeFileSync(join(to, "utils.ts"), readFileSync(join(from, "lib/utils.ts"), "utf8"));
writeFileSync(join(to, "use-media-query.ts"), readFileSync(join(from, "hooks/use-media-query.ts"), "utf8"));
const leftovers = files.flatMap((f) => [...readFileSync(join(to, f), "utf8").matchAll(/from "~\/[^"]+"/g)].map((m) => `${f}: ${m[0]}`));
if (leftovers.length) throw new Error(`Imports the kit cannot resolve:\n${leftovers.join("\n")}`);
writeFileSync(join(to, "index.ts"), `${files.map((f) => `export * from "./${f.replace(/\.tsx$/, "")}";`).join("\n")}\nexport { cn } from "./utils";\n`);
// the fallback variables, so the kit looks like the default theme before /_ws/theme.css loads
const fallback = themeToCss(defaultTheme, { fonts: false }).replace(":root {", ":root {\n  /* generated by scripts/sync.ts from the default theme; /_ws/theme.css overrides this */");
const tokens = readFileSync(join(here, "tokens.template.css"), "utf8").replace("/* @fallback */", fallback.trim());
writeFileSync(join(to, "tokens.css"), tokens);
console.log(`synced ${files.length} components`);
