/// <reference types="node" />
// The generate step of a workspace repo (WORKSPACE-REPO.md §3): reads supergrid.workspace.json and every app folder's
// manifest, and writes `.sg/routes.ts` (the route tree, read by React Router at build time) and `.sg/apps.ts` (the
// registry the Worker composes at run time). Both are plain imports of the app folders, so the build sees every app and
// a clone builds without the desktop. Run by the workspace's Vite config before each dev session and build, and by
// `sg ws generate`.
import { existsSync, mkdirSync, readdirSync, readFileSync, writeFileSync } from "node:fs";
import { join, relative } from "node:path";
// Loaded by Node itself (Vite leaves package imports to it), so the import goes through the package name.
import { checkManifest, type AppManifest } from "@supergrid/app-kit/manifest";

/** `supergrid.workspace.json`: what the workspace is, and what the repo's apps/ folder does not say on its own. */
export type WorkspaceFile = {
  id: string;
  name: string;
  /** Apps to leave out of the build without deleting their folder. */
  disabled?: string[];
  /** Each app's public mount when it differs from its manifest (the sitemap's choice); `null` unmounts its pages. */
  mounts?: Record<string, string | null>;
  /** The page served as `/`. Absent: the first app whose manifest declares `public.home`. */
  home?: { app: string; path: string } | null;
};

export type GeneratedApp = { id: string; dir: string; manifest: AppManifest; problems: string[]; disabled: boolean; hasWorker: boolean; hasRoutes: boolean };
export type Generated = { workspace: WorkspaceFile; apps: GeneratedApp[]; files: string[] };

const HEADER = "// Generated by SuperGrid from supergrid.workspace.json and apps/*/supergrid.app.json. Do not edit; it is rewritten on every dev session and build.\n";
const posix = (p: string) => p.split("\\").join("/");

export function readWorkspaceFile(dir: string): WorkspaceFile {
  const path = join(dir, "supergrid.workspace.json");
  if (!existsSync(path)) throw new Error(`${path} not found: is ${dir} a workspace repo?`);
  const ws = JSON.parse(readFileSync(path, "utf8")) as WorkspaceFile;
  if (typeof ws.id !== "string" || typeof ws.name !== "string") throw new Error(`${path}: id and name are required`);
  return ws;
}

/** The app folders under apps/, each with its manifest read and checked. */
export function readApps(dir: string, ws: WorkspaceFile): GeneratedApp[] {
  const root = join(dir, "apps");
  if (!existsSync(root)) return [];
  const disabled = new Set(ws.disabled ?? []);
  return readdirSync(root).sort().flatMap((folder) => {
    const appDir = join(root, folder);
    const manifestPath = join(appDir, "supergrid.app.json");
    if (!existsSync(manifestPath)) return [];
    let manifest: AppManifest;
    let problems: string[];
    try { manifest = JSON.parse(readFileSync(manifestPath, "utf8")) as AppManifest; problems = checkManifest(manifest); }
    catch (e) { manifest = { id: folder, name: folder, version: "0.0.0" }; problems = [`supergrid.app.json: ${(e as Error).message}`]; }
    if (!problems.length && manifest.id !== folder) problems.push(`the folder is apps/${folder} but the manifest's id is ${manifest.id}; they must match`);
    return [{ id: manifest.id, dir: appDir, manifest, problems, disabled: disabled.has(manifest.id), hasWorker: existsSync(join(appDir, "workers/app.ts")), hasRoutes: existsSync(join(appDir, "app/routes.ts")) }];
  });
}

/** Writes `.sg/routes.ts` and `.sg/apps.ts`. Throws when an app's manifest has problems; a disabled app is skipped, not checked. */
export function generateWorkspace(dir: string): Generated {
  const ws = readWorkspaceFile(dir);
  const all = readApps(dir, ws);
  const bad = all.filter((a) => !a.disabled && a.problems.length);
  if (bad.length) throw new Error(bad.map((a) => `apps/${relative(join(dir, "apps"), a.dir)}:\n${a.problems.map((p) => `  - ${p}`).join("\n")}`).join("\n"));
  const apps = all.filter((a) => !a.disabled);
  const sg = join(dir, ".sg");
  mkdirSync(sg, { recursive: true });
  const rel = (a: GeneratedApp, file: string) => posix(`../${relative(dir, join(a.dir, file))}`);

  const routes = [HEADER, 'import { composeRoutes } from "@supergrid/app-kit/compose";'];
  apps.forEach((a, i) => {
    routes.push(`import m${i} from "${rel(a, "supergrid.app.json")}";`);
    if (a.hasRoutes) routes.push(`import r${i} from "${rel(a, "app/routes")}";`);
  });
  routes.push("");
  routes.push("export default composeRoutes([");
  apps.forEach((a, i) => routes.push(`  { manifest: m${i}, parts: ${a.hasRoutes ? `r${i}` : "{}"}, dir: ${JSON.stringify(posix(`../${relative(dir, join(a.dir, "app"))}`))} },`));
  routes.push(`], ${JSON.stringify({ ...(ws.mounts ? { mounts: ws.mounts } : {}), ...(ws.home !== undefined ? { home: ws.home } : {}) })});`);
  routes.push("");
  writeFileSync(join(sg, "routes.ts"), routes.join("\n"));

  const reg = [HEADER, 'import type { AppModule } from "@supergrid/workspace/worker";'];
  apps.forEach((a, i) => {
    reg.push(`import m${i} from "${rel(a, "supergrid.app.json")}";`);
    if (a.hasWorker) reg.push(`import * as w${i} from "${rel(a, "workers/app")}";`);
  });
  reg.push("");
  reg.push("export const apps: AppModule[] = [");
  apps.forEach((a, i) => reg.push(`  { manifest: m${i}${a.hasWorker ? `, worker: w${i}` : ""} },`));
  reg.push("];");
  reg.push("");
  writeFileSync(join(sg, "apps.ts"), reg.join("\n"));
  return { workspace: ws, apps: all, files: [join(sg, "routes.ts"), join(sg, "apps.ts")] };
}
